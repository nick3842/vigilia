function M.load()
  if vim.g.colors_name then vim.cmd("highlight clear") end
  if vim.fn.exists("syntax_on") == 1 then vim.cmd("syntax reset") end
  vim.o.termguicolors = true
  vim.g.colors_name = "vigilia"

  for group, spec in pairs(highlights(M.palette)) do
    vim.api.nvim_set_hl(0, group, spec)
  end

  local c = M.palette
  local terminal = {
    c.midnight, c.red, c.green, c.gold, c.fjord, c.rose, c.pale_blue, c.cream,
    c.steel, c.pale_rose, "#A8C9AE", c.pale_gold, c.pale_blue, "#CE8790", "#85C6D3", "#FFFDF7",
  }
  for i, color in ipairs(terminal) do
    vim.g["terminal_color_" .. (i - 1)] = color
  end
end

return M
